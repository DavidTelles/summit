class Grid {
    constructor(w, h) {
        this.w = w;
        this.h = h;
        this.cells = Array.from({ length: h }, () => Array(w).fill('.'));
    }

    set(x, y, c) {
        if (x >= 0 && x < this.w && y >= 0 && y < this.h) this.cells[y][x] = c;
        return this;
    }

    fill(x1, y1, x2, y2, c) {
        for (let y = y1; y <= y2; y++) for (let x = x1; x <= x2; x++) this.set(x, y, c);
        return this;
    }

    many(list, c) {
        list.forEach(([x, y]) => this.set(x, y, c));
        return this;
    }
}

